import {
  AlignmentType,
  BorderStyle,
  Document,
  HeadingLevel,
  Packer,
  PageBreak,
  Paragraph,
  TextRun,
} from "docx";

const LETTERS = ["A", "B", "C", "D"];
const FONT = "Arial";

function slugify(text) {
  return (
    text
      .toLowerCase()
      .replace(/[^a-z0-9]+/g, "-")
      .replace(/^-+|-+$/g, "")
      .slice(0, 50) || "quiz"
  );
}

export function quizFileName(quiz) {
  return `${slugify(quiz.title)}.docx`;
}

export function buildQuizDocument(quiz) {
  const children = [];

  // Header
  children.push(
    new Paragraph({
      heading: HeadingLevel.TITLE,
      alignment: AlignmentType.CENTER,
      spacing: { after: 120 },
      children: [new TextRun({ text: quiz.title, bold: true, size: 40, font: FONT })],
    }),
    new Paragraph({
      alignment: AlignmentType.CENTER,
      spacing: { after: 240 },
      border: { bottom: { style: BorderStyle.SINGLE, size: 8, color: "4F46E5", space: 6 } },
      children: [
        new TextRun({
          text: "20-Item Multiple Choice Quiz  |  Generated by TwentyQ",
          size: 20,
          color: "6B7280",
          font: FONT,
        }),
      ],
    }),
    new Paragraph({
      spacing: { before: 120, after: 120 },
      children: [
        new TextRun({ text: "Name: ______________________________", size: 22, font: FONT }),
        new TextRun({ text: "          Date: _______________", size: 22, font: FONT }),
      ],
    }),
    new Paragraph({
      spacing: { after: 240 },
      children: [
        new TextRun({ text: "Directions: ", bold: true, size: 22, font: FONT }),
        new TextRun({
          text: "Choose the best answer for each question. Circle the letter of your answer.",
          italics: true,
          size: 22,
          font: FONT,
        }),
      ],
    })
  );

  // Questions
  quiz.questions.forEach((q, i) => {
    children.push(
      new Paragraph({
        keepNext: true,
        keepLines: true,
        spacing: { before: 200, after: 80 },
        indent: { left: 432, hanging: 432 },
        children: [
          new TextRun({ text: `${i + 1}.\t`, bold: true, size: 22, font: FONT }),
          new TextRun({ text: q.question, size: 22, font: FONT }),
        ],
      })
    );
    q.choices.forEach((choice, c) => {
      children.push(
        new Paragraph({
          keepNext: c < 3,
          keepLines: true,
          spacing: { after: 40 },
          indent: { left: 864, hanging: 360 },
          children: [
            new TextRun({ text: `${LETTERS[c]}.\t`, size: 22, font: FONT }),
            new TextRun({ text: choice, size: 22, font: FONT }),
          ],
        })
      );
    });
  });

  // Answer key (new page)
  children.push(
    new Paragraph({ children: [new PageBreak()] }),
    new Paragraph({
      heading: HeadingLevel.HEADING_1,
      spacing: { after: 200 },
      border: { bottom: { style: BorderStyle.SINGLE, size: 6, color: "4F46E5", space: 4 } },
      children: [new TextRun({ text: "Answer Key", bold: true, size: 32, font: FONT })],
    })
  );

  quiz.questions.forEach((q, i) => {
    children.push(
      new Paragraph({
        spacing: { after: 80 },
        indent: { left: 432, hanging: 432 },
        children: [
          new TextRun({ text: `${i + 1}.\t`, bold: true, size: 22, font: FONT }),
          new TextRun({ text: `${LETTERS[q.answer]}. ${q.choices[q.answer]}`, bold: true, size: 22, font: FONT }),
          ...(q.explanation
            ? [new TextRun({ text: `  |  ${q.explanation}`, size: 20, color: "6B7280", font: FONT })]
            : []),
        ],
      })
    );
  });

  return new Document({
    creator: "TwentyQ",
    title: quiz.title,
    styles: { default: { document: { run: { font: FONT, size: 22 } } } },
    sections: [
      {
        properties: {
          page: {
            size: { width: 12240, height: 15840 }, // US Letter
            margin: { top: 1440, right: 1440, bottom: 1440, left: 1440 },
          },
        },
        children,
      },
    ],
  });
}

export async function downloadQuizDocx(quiz) {
  const blob = await Packer.toBlob(buildQuizDocument(quiz));
  const url = URL.createObjectURL(blob);
  const a = document.createElement("a");
  a.href = url;
  a.download = quizFileName(quiz);
  document.body.appendChild(a);
  a.click();
  a.remove();
  setTimeout(() => URL.revokeObjectURL(url), 1000);
}
